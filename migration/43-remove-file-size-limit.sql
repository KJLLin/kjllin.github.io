-- ============================================================================
-- 43-remove-file-size-limit.sql
--
-- 取消云盘的单文件 10MB 限制。
--
-- 说明：
--   * 桶级 file_size_limit 置空后，回落到项目的全局上限（当前套餐为 50MB）。
--     这是 Supabase 平台上限，前端无法突破；私有空间仍受每人 50MB 配额约束。
--   * 前端已去掉 10MB 预检，上传时若被平台以 413 拒绝，会提示「服务器单文件上限」。
-- ============================================================================

update storage.buckets
   set file_size_limit = null
 where id in ('cloud-drive', 'cloud-drive-private');
